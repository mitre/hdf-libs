// Regenerate with:
//
//	go test ./internal/mcp/evalharness -run TestEnvelopeGolden -update-envelopes
var updateEnvelopes = flag.Bool("update-envelopes", false,
	"rewrite testdata/mcp-envelopes.golden.json from live tool replies")

// The paged tools and the arguments that produce a reply worth publishing as an example.
// Sources are repo-relative so the handle the MCP embeds encodes a stable path.
var envelopeCalls = []struct {
	tool string
	args map[string]any
}{
	{
		tool: "hdf_query",
		args: map[string]any{
			"source":    map[string]any{"path": "hdf-fixtures/results/inspec-multilayered.json"},
			"verbosity": "full",
			"limit":     2,
		},
	},
	{
		tool: "hdf_diff",
		args: map[string]any{
			"from":      map[string]any{"path": "hdf-cli/internal/mcp/tools/testdata/diff-from.json"},
			"to":        map[string]any{"path": "hdf-cli/internal/mcp/tools/testdata/diff-to.json"},
			"verbosity": "full",
		},
	},
}

// captureEnvelopes drives each paged tool and returns its RAW structuredContent.
//
// Raw on purpose: ADR-0008 §2's rewrite map lives in the API generator, and applying it
// here would put the projection in two languages.
func captureEnvelopes(t *testing.T) map[string]any {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", "..", "..", ".."))
	if err != nil {
		t.Fatalf("resolving the repo root: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "hdf-fixtures")); err != nil {
		t.Fatalf("%s is not the repo root: %v", root, err)
	}
	t.Setenv("HDF_MCP_ROOT", root)

	requests := make([]protocolRequest, 0, len(envelopeCalls))
	for _, call := range envelopeCalls {
		requests = append(requests, protocolRequest{
			label:  call.tool,
			method: "tools/call",
			params: map[string]any{"name": call.tool, "arguments": call.args},
		})
	}
	results := driveRequests(t, func(s *sdkmcp.Server) { tools.RegisterAll(s) }, requests)

	captures := make(map[string]any, len(results))
	for _, call := range envelopeCalls {
		var reply struct {
			StructuredContent map[string]any `json:"structuredContent"`
			IsError           bool           `json:"isError"`
		}
		if err := json.Unmarshal(results[call.tool], &reply); err != nil {
			t.Fatalf("%s: unmarshalling the reply: %v", call.tool, err)
		}
		if reply.IsError {
			t.Fatalf("%s returned an error reply: %s", call.tool, results[call.tool])
		}
		if len(reply.StructuredContent) == 0 {
			t.Fatalf("%s returned no structuredContent", call.tool)
		}
		captures[call.tool] = reply.StructuredContent
	}
	return captures
}

func TestEnvelopeGolden_MatchesLive(t *testing.T) {
	live := map[string]any{
		"$comment": "Generated by TestEnvelopeGolden_MatchesLive — regenerate with " +
			"-update-envelopes and review the diff. Each entry is one paged tool's RAW reply; " +
			"the ADR-0008 API generator projects it into that operation's 200 example. " +
			"hdf_convert is absent on purpose: its reply carries sha256 of the converted " +
			"document and the converter stamps time.Now(), so no capture of it is stable.",
		"captures": captureEnvelopes(t),
	}
	serialised, err := json.MarshalIndent(live, "", "  ")
	if err != nil {
		t.Fatalf("serialising the captures: %v", err)
	}
	serialised = append(serialised, '\n')

	path := filepath.Join("testdata", "mcp-envelopes.golden.json")
	if *updateEnvelopes {
		if err := os.WriteFile(path, serialised, 0o600); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}
		t.Logf("rewrote %s — review the diff", path)
		return
	}

	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v\nregenerate with: go test ./internal/mcp/evalharness -run TestEnvelopeGolden -update-envelopes", path, err)
	}
	if string(committed) != string(serialised) {
		t.Errorf("the live replies differ from the golden. If a tool's response changed on "+
			"purpose, regenerate and review the diff:\n"+
			"  go test ./internal/mcp/evalharness -run TestEnvelopeGolden -update-envelopes\n"+
			"  committed %d bytes, live %d bytes", len(committed), len(serialised))
	}
}

// A capture that is not byte-stable would make the golden churn on every run.
func TestEnvelopeGolden_CaptureIsDeterministic(t *testing.T) {
	first, err := json.Marshal(captureEnvelopes(t))
	if err != nil {
		t.Fatalf("marshalling the first capture: %v", err)
	}
	second, err := json.Marshal(captureEnvelopes(t))
	if err != nil {
		t.Fatalf("marshalling the second capture: %v", err)
	}
	if string(first) != string(second) {
		t.Errorf("two captures of the same fixtures differ, so the golden cannot be stable")
	}
}

// Every configured call produced a capture. Which tools NEED one is decided by the
// binding table, so that accounting lives in hdf-openapi's suite.
func TestEnvelopeGolden_EveryCallIsCaptured(t *testing.T) {
	captures := captureEnvelopes(t)
	if len(captures) != len(envelopeCalls) {
		t.Fatalf("captured %d replies for %d calls", len(captures), len(envelopeCalls))
	}
	for _, call := range envelopeCalls {
		if _, ok := captures[call.tool]; !ok {
			t.Errorf("no capture for %s", call.tool)
		}
	}
}
