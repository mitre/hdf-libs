#!/usr/bin/env node
// Regenerates nist-rev4-withdrawn.json from NIST's SP 800-53 Rev 4 control catalog:
//   node scripts/generate-nist-rev4-withdrawn.mjs <800-53-rev4-controls.xml> [--check]
// Each control Rev 4 lists as withdrawn keeps the controls NIST says it went into; a
// target that is not a control is printed and left out. --check exits 1 on drift.
// Provenance: hdf-mappings/README.md, "Rev 4 withdrawn controls".

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'go', 'datasets', 'mappings', 'nist-rev4-withdrawn.json');

const CONTROL = /^[A-Z]{2}-\d+(?: \(\d+\))?$/;

// "AC-17 (8)" as the crosswalk rosters write it: "AC-17(8)".
const compact = (id) => id.replace(' (', '(');

export function parseWithdrawn(xml) {
  const withdrawn = {};
  const skipped = [];
  // A control's own <number> precedes its enhancements; each part is one item.
  const items = xml.split(/(?=<(?:\w+:)?control>)|(?=<control-enhancement>)/);
  for (const item of items) {
    const number = /<number>([^<]+)<\/number>/.exec(item)?.[1].trim();
    const block = /<withdrawn>([\s\S]*?)<\/withdrawn>/.exec(item)?.[1];
    if (!number || block === undefined) continue;
    if (!CONTROL.test(number)) throw new Error(`withdrawn item is not a control identifier: ${number}`);
    if (compact(number) in withdrawn) throw new Error(`${number}: withdrawn twice`);
    const targets = [];
    for (const m of block.matchAll(/<incorporated-into>([^<]+)<\/incorporated-into>/g)) {
      const target = m[1].trim();
      if (!CONTROL.test(target)) {
        skipped.push(`${number}: ${JSON.stringify(target)}`);
        continue;
      }
      if (!targets.includes(compact(target))) targets.push(compact(target));
    }
    withdrawn[compact(number)] = targets;
  }
  const marked = (xml.match(/<withdrawn>/g) ?? []).length;
  const ids = Object.keys(withdrawn);
  if (ids.length !== marked) throw new Error(`parsed ${ids.length} withdrawn items of ${marked}`);
  // A target that is itself withdrawn would place a reference on a control Rev 4 lacks.
  for (const id of ids) {
    const chained = withdrawn[id].filter((t) => t in withdrawn);
    if (chained.length) throw new Error(`${id}: incorporated into withdrawn ${chained.join(', ')}`);
  }
  return { withdrawn, skipped };
}

function serialize(withdrawn, sha256) {
  const sorted = Object.fromEntries(Object.keys(withdrawn).sort().map((k) => [k, withdrawn[k]]));
  const doc = {
    $comment:
      'Generated by hdf-mappings/scripts/generate-nist-rev4-withdrawn.mjs from NIST SP 800-53 Rev 4 control catalog. Do not hand-edit; rerun the script.',
    source: { file: '800-53-rev4-controls.xml', sha256 },
    withdrawn: sorted,
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const input = args.find((a) => !a.startsWith('--'));
  if (!input) {
    console.error('usage: generate-nist-rev4-withdrawn.mjs <path/to/800-53-rev4-controls.xml> [--check]');
    process.exit(2);
  }
  const bytes = readFileSync(input);
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const { withdrawn, skipped } = parseWithdrawn(bytes.toString('utf8'));
  const out = serialize(withdrawn, sha256);

  const ids = Object.keys(withdrawn);
  console.log(`800-53 Rev 4 catalog sha256 ${sha256}`);
  console.log(`${ids.length} withdrawn; ${ids.filter((id) => !withdrawn[id].length).length} with no control successor`);
  for (const s of skipped) console.log(`not a control, left out: ${s}`);

  if (check) {
    if (readFileSync(OUT, 'utf8') !== out) {
      console.error('nist-rev4-withdrawn.json is out of date; rerun without --check');
      process.exit(1);
    }
    console.log('nist-rev4-withdrawn.json is current');
    return;
  }
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
